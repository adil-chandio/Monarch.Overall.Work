#!/usr/bin/env python3
"""Regenerate the headless stub libraries for bpy.

Blender's bundled modules reference X11 / XKB / GLX / core-GL entry points even when
rendering offline, and a slim container has no libX11 and no root to install one.
This scans bpy's own shared objects for the symbols they need, then emits C stubs.

Two outputs, because the loader checks symbol *versions* per library:
  x11_shim/libx11shim.so       free symbols (X11, GLX, core GL, XInput, XFixes)
  x11_shim/libxkbcommon.so.0   xkb* symbols, exported under the version tag the
                               caller asks for (V_0.5.0)

Run after a bpy upgrade, then build with x11_shim/build_x11_shim.sh.
"""
import glob
import os
import subprocess
import sys

BPY = os.environ.get("BPY_DIR", "/usr/local/lib/python3.11/dist-packages/bpy")
HERE = os.path.dirname(os.path.abspath(__file__))
SHIM = os.path.join(HERE, "x11_shim")
MANUAL = {"glFinish", "glFlush", "glPixelStorei"}
XKB_PREFIXES = ("xkb_", "_xkb_")
PREFIXES = ("X", "gl", "GL", "_Xi", "_Xim", "XI")


def _nm(args, lib):
    return subprocess.run(["nm", "-D", args, lib], capture_output=True, text=True).stdout


def scan():
    libs = [os.path.join(BPY, "__init__.so")] + glob.glob(os.path.join(BPY, "lib", "*.so*"))
    if not os.path.exists(libs[0]):
        sys.exit(f"bpy not found at {BPY}; set BPY_DIR")
    defined = set()
    for lib in libs:
        for line in _nm("--defined-only", lib).splitlines():
            parts = line.split()
            if len(parts) >= 3:
                defined.add(parts[2])
    needed = {}
    for lib in libs:
        for line in _nm("--undefined-only", lib).splitlines():
            parts = line.split()
            if len(parts) < 2:
                continue
            sym, _, ver = parts[1].partition("@")
            if sym in defined:
                continue
            if sym.startswith(XKB_PREFIXES):
                needed[sym] = ver
            elif sym.startswith(PREFIXES):
                needed[sym] = ver
    return needed


def write(path, symbols, header, versions=None):
    stubs = "\n".join(f"long {s}(void) {{ return 0; }}" for s in symbols)
    with open(path, "w") as f:
        f.write(header + stubs + "\n")


def main():
    needed = scan()
    xkb = sorted(s for s in needed if s.startswith(XKB_PREFIXES))
    x11 = sorted(s for s in needed if not s.startswith(XKB_PREFIXES) and s not in MANUAL)

    generic = """/* AUTO-GENERATED by tools/blender_local/gen_shims.py — do not edit.
 *
 * Stub bindings for X11 / GLX / core-GL symbols that headless bpy references.
 * Each returns 0/NULL. This is NOT an X11 or OpenGL implementation: the GUI and
 * viewport cannot run on it. It exists so `import bpy` and Cycles CPU rendering
 * work in a container without libX11 and without root.
 */
#include <stddef.h>

"""
    manual = """
/* handwritten: real signatures, no-op bodies */
void glFinish(void) {}
void glFlush(void) {}
void glPixelStorei(unsigned int p, int v) { (void)p; (void)v; }
"""
    with open(os.path.join(SHIM, "x11_gl_stubs.c"), "w") as f:
        f.write(generic + "\n".join(f"long {s}(void) {{ return 0; }}" for s in x11) + "\n" + manual)

    xkb_c = """/* AUTO-GENERATED by tools/blender_local/gen_shims.py — do not edit.
 *
 * Stub libxkbcommon: keyboard handling only. Headless rendering never asks for a
 * key, but the loader must find these symbols under the version tags that bpy
 * requests, so they are exported inside `V_0.5.0`.
 */
#include <stddef.h>

"""
    write(os.path.join(SHIM, "xkb_stubs.c"), xkb, xkb_c)
    with open(os.path.join(SHIM, "libxkbcommon_ver.map"), "w") as f:
        f.write("V_0.5.0 { global: *; };\n")
    print(f"x11/gl symbols: {len(x11)}   xkb symbols: {len(xkb)}")


if __name__ == "__main__":
    main()
